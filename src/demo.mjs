// `pilot journal --md`: render journal entries (one or more JSONL files) into DEMO.md. Every
// figure comes from the journal rows; receipts (status/block/gas) come from a refetch file made
// by scripts/refetch.mjs, which re-reads each tx from the RPC. Nothing is typed in by hand.
const short = (h) => (h ? `${h.slice(0, 10)}…${h.slice(-6)}` : "-");
const cell = (v) => String(v ?? "-").replace(/\|/g, "\\|").replace(/\n/g, " ");

export const parseReceipts = (text) => {
  const m = new Map();
  for (const l of text.split("\n")) {
    const [hash, status, block, , gas] = l.trim().split(/\s+/);
    if (/^0x[0-9a-f]{64}$/.test(hash ?? "")) m.set(hash, { status, block, gas });
  }
  return m;
};

export const renderDemo = (entries, { receipts = new Map(), title = "pilot — DEMO", sources = [] } = {}) => {
  const rows = [...entries].sort((a, b) => String(a.at).localeCompare(String(b.at)));
  const by = (k) => rows.filter((e) => e.kind === k);
  const orders = by("order");
  const closes = by("close");
  const brackets = by("bracket");
  const cancels = by("cancel").filter((e) => e.txs?.length);
  const refusals = by("refusal");
  const notes = by("note");
  const byPilot = refusals.filter((e) => e.refused_by === "pilot-policy");
  const byExchange = refusals.filter((e) => e.refused_by === "exchange");
  const rc = (tx) => {
    const r = receipts.get(tx);
    return r ? `${r.status} @ block ${r.block}, ${r.gas} gas` : "not re-fetched";
  };
  const out = [];
  out.push(`# ${title}`, "", "Generated by `pilot journal --md` from the append-only journal. Every figure below is a row of that journal;");
  out.push("the transaction status/block/gas column is re-read from the Somnia Hideki testnet RPC (`scripts/refetch.mjs`).", "");
  if (sources.length) out.push(`Journals rendered: ${sources.map((s) => `\`${s}\``).join(", ")}`, "");
  out.push("## Summary", "");
  out.push(`- Real orders opened through the MCP tools: **${orders.length}**`);
  out.push(`- Positions closed: **${closes.length}**`);
  out.push(`- Brackets armed (take-profit + stop-loss): **${brackets.length}**`);
  out.push(`- Cancels that sent a transaction: **${cancels.length}**`);
  out.push(`- Refusals by pilot's policy: **${byPilot.length}**; refusals by the exchange: **${byExchange.length}**`, "");
  const tx = (list, head, line) => {
    if (!list.length) return;
    out.push(`## ${head}`, "", "| time (UTC) | what | tx | on chain (RPC re-fetch) |", "|---|---|---|---|");
    for (const e of list) out.push(`| ${cell(e.at)} | ${cell(line(e))} | \`${e.tx ?? "-"}\` | ${cell(rc(e.tx))} |`);
    out.push("");
  };
  tx(orders, "Orders", (e) => `${e.direction ?? e.side} ${e.size} ${e.market} (IOC, limit ${e.limitPrice}), filled ${e.filled}, position after ${e.positionAfter}`);
  tx(closes, "Closes", (e) => `${e.direction ?? e.side} ${e.size} ${e.market} (IOC, limit ${e.limitPrice}), position after ${e.positionAfter}`);
  tx(brackets, "Brackets", (e) => `${e.side} ${e.size} ${e.market}: take-profit ${e.takeProfitTrigger} (stop #${e.takeProfitStopId}), stop-loss ${e.stopLossTrigger} (stop #${e.stopLossStopId})`);
  if (cancels.length) {
    out.push("## Cancels", "", "| time (UTC) | what | tx | on chain (RPC re-fetch) |", "|---|---|---|---|");
    for (const e of cancels) for (const t of e.txs) out.push(`| ${cell(e.at)} | ${cell(t.what)} | \`${t.tx}\` | ${cell(rc(t.tx))} |`);
    out.push("");
  }
  const refusalLine = (e) => {
    const first = e.refusals?.[0];
    const rule = e.rules?.join(", ") ?? e.code ?? "-";
    const why = e.reason ?? first?.detail ?? "-";
    const ask = e.size ?? e.requestedSize;
    return `| ${cell(e.at)} | ${cell(e.stage)} | ${cell([e.side, ask, e.market].filter(Boolean).join(" "))} | ${cell(rule)} | ${cell(why)} | ${cell(e.next ?? first?.next)} |`;
  };
  if (byPilot.length) {
    out.push("## Refusals by pilot's policy (`refused_by: \"pilot-policy\"`)", "", "No transaction was sent for any of these.", "", "| time (UTC) | stage | order | rule | why | next safe action |", "|---|---|---|---|---|---|");
    for (const e of byPilot) out.push(refusalLine(e));
    out.push("");
  }
  if (byExchange.length) {
    out.push("## Refusals by the exchange (`refused_by: \"exchange\"`)", "", "The order passed pilot's policy, was sent, and the exchange reverted it. The reason is the decoded custom error. If a note at the end says the race was injected, the exchange saw a real order and refused it for real; only the price move that made it unfillable was staged.", "", "| time (UTC) | stage | order | error | reason | next safe action | tx |", "|---|---|---|---|---|---|---|");
    for (const e of byExchange) out.push(`${refusalLine(e)} \`${e.tx ?? "-"}\` (${cell(rc(e.tx))}) |`);
    out.push("");
  }
  if (notes.length) {
    out.push("## Notes recorded in the journal", "");
    for (const e of notes) out.push(`- ${cell(e.at)}: ${e.text}`);
    out.push("");
  }
  return out.join("\n") + "\n";
};
