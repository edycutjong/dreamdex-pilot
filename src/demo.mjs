// `pilot journal --md`: render journal entries (one or more JSONL files) into DEMO.md. Every
// figure comes from the journal rows; receipts (status/block/gas) come from a refetch file made
// by scripts/refetch.mjs, which re-reads each tx from the RPC. Nothing is typed in by hand.
import { LIMIT_RULES } from "./policy.mjs";

// A refusal row is "by my limits" when one of its rules is a policy limit (LIMIT_RULES); the rest are
// pilot's own checks (a size under the market minimum, an unknown, used or expired plan, ...).
const isLimit = (e) => (e.rules ?? []).some((r) => LIMIT_RULES.includes(r));
const isFlat = (e) => e.positionAfter === "0";

const short = (h) => (h ? `${h.slice(0, 10)}…${h.slice(-6)}` : "-");
const cell = (v) => String(v ?? "-").replace(/\|/g, "\\|").replace(/\n/g, " ");
// dreamDEX's markets explorer for the Hideki testnet (listed on its perps testnet docs page). /tx/<hash> shows the market events of a
// tx (fills); a stop placement, a cancel or a reverted tx shows "Nothing indexed for this transaction", so only orders and closes link.
export const EXPLORER = "https://smk-dev-markets-explorer-hideki-euw4-uzavbo36ra-ez.a.run.app";
const txLink = (h, explorer) => (explorer && /^0x[0-9a-f]{64}$/i.test(h ?? "") ? `[\`${h}\`](${explorer}/tx/${h})` : `\`${h ?? "-"}\``);

export const parseReceipts = (text) => {
  const m = new Map();
  for (const l of text.split("\n")) {
    const [hash, status, block, , gas] = l.trim().split(/\s+/);
    if (/^0x[0-9a-f]{64}$/.test(hash ?? "")) m.set(hash, { status, block, gas });
  }
  return m;
};

export const renderDemo = (entries, { receipts = new Map(), title = "pilot — DEMO", sources = [], legend, explorer = EXPLORER } = {}) => {
  const rows = [...entries].sort((a, b) => String(a.at).localeCompare(String(b.at)));
  const by = (k) => rows.filter((e) => e.kind === k);
  const orders = by("order");
  const closes = by("close");
  const brackets = by("bracket");
  const cancels = by("cancel").filter((e) => e.txs?.length);
  const refusals = by("refusal");
  const notes = by("note");
  // The plan an order was sent from carries what plan_order showed before the send (margin, leverage, liquidation).
  const plans = new Map(by("plan").map((e) => [e.plan_id, e]));
  const planned = (e) => {
    const p = plans.get(e.plan_id);
    if (!p) return "";
    const liq = p.liquidationPrice != null ? `liquidation ${Number(p.liquidationPrice).toFixed(2)} (${p.liquidationDistancePct}% from mark)` : (p.liquidationNote ?? "liquidation unknown");
    return `; planned: margin $${p.marginLockUsd}, ${p.projectedLeverageX}x leverage, ${liq}`;
  };
  const byPilot = refusals.filter((e) => e.refused_by === "pilot-policy");
  const byExchange = refusals.filter((e) => e.refused_by === "exchange");
  const rc = (tx) => {
    const r = receipts.get(tx);
    return r ? `${r.status} @ block ${r.block}, ${r.gas} gas` : "not re-fetched";
  };
  const out = [];
  out.push(`# ${title}`, "", "Generated by `pilot journal --md` from the append-only journal. Every figure in the tables below is a row of those journals;");
  out.push("the transaction status/block/gas column is re-read from the Somnia Hideki testnet RPC (`scripts/refetch.mjs`); Hideki is the chain the bounty listing calls the Somnia Tokyo testnet.", "");
  if (explorer) out.push(`Order and close hashes link to their fills on dreamDEX's Hideki markets explorer (${explorer}). That explorer shows nothing for bracket, cancel and reverted transactions ("Nothing indexed for this transaction"), so those are checked by the RPC column only.`, "");
  if (sources.length) out.push(`Journals rendered: ${sources.map((s) => `\`${s}\``).join(", ")}`, "");
  if (legend) out.push(`Clients: ${legend}`, "");
  out.push("The summary counts the journals listed above; attempts described only in a note are not in it.", "");
  out.push("## Summary", "");
  out.push(`- Real orders opened through the MCP tools: **${orders.length}**`);
  // A close is an IOC: it can fill part of the position, and its read-back can fail. Only a close whose
  // read-back says flat counts as a position closed.
  const flat = closes.filter(isFlat);
  out.push(`- Positions closed (flat on the read-back after the close): **${flat.length}**${closes.length > flat.length ? `; **${closes.length - flat.length}** more close transactions left a position or had no read-back` : ""}`);
  out.push(`- Brackets armed (take-profit + stop-loss): **${brackets.length}**`);
  out.push(`- Cancels that sent a transaction: **${cancels.length}**`);
  const injected = byExchange.filter((e) => e.injected);
  const distinct = new Set(byPilot.flatMap((e) => e.rules ?? [])).size;
  const limited = byPilot.filter(isLimit);
  const named = (rows, keep) => [...new Set(rows.flatMap((e) => e.rules ?? []).filter(keep))].join(", ");
  const split = byPilot.length ? `: **${limited.length}** by the policy limits (${named(limited, (r) => LIMIT_RULES.includes(r)) || "none"}), **${byPilot.length - limited.length}** by pilot's own checks (${named(byPilot.filter((e) => !isLimit(e)), () => true) || "none"})` : "";
  out.push(`- Refusals by pilot's policy: **${byPilot.length}** rows (**${distinct}** distinct rules)${split}; refusals by the exchange: **${byExchange.length}**${injected.length ? ` (${injected.length} of them with the race injected: the limit price was lowered in the sender so the order was unfillable by construction, no natural race; see Notes)` : ""}`, "");
  // The refusal a judge should see first, before the tables: the newest one by the position cap.
  const cap = byPilot.filter((e) => e.rules?.includes("maxNotionalUsd") && e.positionNow != null && e.positionNow !== "0").at(-1);
  if (cap) {
    const r = cap.refusals.find((x) => x.rule === "maxNotionalUsd");
    out.push("## The refusal to look at first", "", `${cap.at}: with ${cap.positionNow} ${cap.market} already open, a ${cap.side} of ${cap.size} ${cap.market} (an order of $${Number(cap.notionalUsd).toFixed(2)}) was refused and nothing was sent.`, "", `- why: ${r.detail}`, `- next safe action: ${r.next}`, "");
  }
  const tx = (list, head, line, link = true) => {
    if (!list.length) return;
    out.push(`## ${head}`, "", "| time (UTC) | what | tx | on chain (RPC re-fetch) | journal |", "|---|---|---|---|---|");
    for (const e of list) out.push(`| ${cell(e.at)} | ${cell(line(e))} | ${txLink(e.tx, link && explorer)} | ${cell(rc(e.tx))} | ${cell(e._src)} |`);
    out.push("");
  };
  tx(orders, "Orders", (e) => `${e.direction ?? e.side} ${e.size} ${e.market} (IOC, limit ${e.limitPrice}), filled ${e.filled}, position after ${e.positionAfter}${planned(e)}`);
  tx(closes, "Closes", (e) => `${e.direction ?? e.side} ${e.size} ${e.market} (IOC, limit ${e.limitPrice}), position after ${e.positionAfter}`);
  tx(brackets, "Brackets", (e) => `${e.side} ${e.size} ${e.market}: take-profit ${e.takeProfitTrigger} (stop #${e.takeProfitStopId}), stop-loss ${e.stopLossTrigger} (stop #${e.stopLossStopId})${e.sttHeldUntilCancel != null ? `, ${e.sttHeldUntilCancel} STT held until it fires or is cancelled` : ""}${e.operatorGrantTxs?.length ? `; first bracket, the SDK also sent the one-time operator grant ${e.operatorGrantTxs.join(", ")}` : ""}`, false);
  if (cancels.length) {
    out.push("## Cancels", "", "| time (UTC) | what | tx | on chain (RPC re-fetch) | journal |", "|---|---|---|---|---|");
    for (const e of cancels) for (const t of e.txs) out.push(`| ${cell(e.at)} | ${cell(t.what)} | \`${t.tx}\` | ${cell(rc(t.tx))} | ${cell(e._src)} |`);
    out.push("");
  }
  const refusalLine = (e) => {
    if (e.injected && e.refused_by === "exchange")
      return `| ${cell(e.at)} | ${cell(e.stage)} | ${cell([e.side, e.size, e.market].join(" "))} **(race injected, sent at ${cell(e.sentLimitPrice ?? "a lowered limit")})** | ${cell(e.code)} | ${cell(e.reason)} | plan again from a fresh touch |`;
    const first = e.refusals?.[0];
    const rule = e.rules?.join(", ") ?? e.code ?? "-";
    const why = e.reason ?? first?.detail ?? "-";
    const ask = e.size ?? e.requestedSize;
    // A place-stage refusal of a plan names only the plan_id: show that rather than an empty cell.
    const what = [e.side, ask, e.market].filter(Boolean).join(" ") || (e.plan_id ? `plan ${e.plan_id}` : "-");
    return `| ${cell(e.at)} | ${cell(e.stage)} | ${cell(what)} | ${cell(rule)} | ${cell(why)} | ${cell(e.next ?? first?.next)} |`;
  };
  if (byPilot.length) {
    out.push("## Refusals by pilot's policy (`refused_by: \"pilot-policy\"`)", "", "No transaction was sent for any of these. Counts are rows: some are scripted probes (for example a deliberately made-up plan id) or the same prompt run again.", "", "| time (UTC) | stage | order | rule | why | next safe action |", "|---|---|---|---|---|---|");
    for (const e of byPilot) out.push(refusalLine(e));
    out.push("");
  }
  if (byExchange.length) {
    out.push("## Refusals by the exchange (`refused_by: \"exchange\"`)", "", "The order passed pilot's policy and was sent; the exchange reverted it and the reason is the decoded custom error. Rows marked **race injected** were provoked on purpose: the limit price was lowered in the sender before sending (see Notes), so the order was unfillable by construction (no natural race). The revert, the decoded reason and the tx are real.", "", "| time (UTC) | stage | order | error | reason | next safe action | tx |", "|---|---|---|---|---|---|---|");
    for (const e of byExchange) out.push(`${refusalLine(e)} \`${e.tx ?? "-"}\` (${cell(rc(e.tx))}) |`);
    out.push("");
  }
  if (notes.length) {
    out.push("## Notes recorded in the journal", "");
    for (const e of notes) out.push(`- ${cell(e.at)}: ${e.text}`);
    out.push("");
  }
  return out.join("\n") + "\n";
};

// `pilot journal --card`: a short text receipt of your own journal, sized for a post (X counts a link
// as 23 characters), with your latest fill on the explorer and a link back to pilot.
export const REPO = "https://github.com/edycutjong/dreamdex-pilot";
export const renderCard = (entries, { explorer = EXPLORER, repo = REPO } = {}) => {
  const by = (k) => entries.filter((e) => e.kind === k);
  const refusals = by("refusal").filter((e) => e.refused_by === "pilot-policy");
  const fills = [...by("order"), ...by("close")].filter((e) => /^0x[0-9a-f]{64}$/i.test(e.tx ?? ""));
  const last = fills.sort((a, b) => String(a.at).localeCompare(String(b.at))).at(-1);
  return [
    "My dreamDEX perps receipts via pilot (Somnia testnet) @DreamDEXSomnia:",
    `${by("order").length} orders opened, ${by("close").filter(isFlat).length} closed${by("close").some((e) => !isFlat(e)) ? ` (+${by("close").filter((e) => !isFlat(e)).length} not confirmed flat)` : ""}, ${by("bracket").length} brackets, ${refusals.length} refused with nothing sent (${refusals.filter(isLimit).length} by my limits).`,
    ...(last ? [`Latest fill: ${explorer}/tx/${last.tx}`] : []),
    repo,
  ].join("\n") + "\n";
};
